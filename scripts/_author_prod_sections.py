def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    entries = []
    with open(CATALOG, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                entries.append(json.loads(line))

    written, skipped = [], []
    for e in entries:
        patch = SECTIONS.get(e["id"])
        if not patch:
            continue
        if "sections" in e:
            skipped.append(e["id"])
            continue
        e["elements_note"] = patch["elements_note"]
        e["sections"] = patch["sections"]
        written.append(e["id"])

    print(f"补写: {len(written)} 个 {written}")
    if skipped:
        print(f"跳过(已有 sections): {skipped}")

    if args.dry_run:
        print("\n--dry-run, 未写入")
        return 0

    bk = os.path.join(os.path.dirname(CATALOG), f"catalog.bak_{datetime.now():%Y%m%d_%H%M%S}.jsonl")
    shutil.copy2(CATALOG, bk)
    print(f"已备份 → {os.path.relpath(bk, ROOT)}")
    with open(CATALOG, "w", encoding="utf-8") as f:
        for e in entries:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")
    print(f"已写回 {CATALOG} ({len(entries)} 条)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
